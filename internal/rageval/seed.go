package rageval

import (
	"hash/fnv"
	"regexp"
	"sort"
	"strings"
)

// SeedDoc is one stored source the seed draws questions from.
type SeedDoc struct {
	URI  string
	Text string
}

// SeedOpts bounds how many cases each kind of seed contributes.
type SeedOpts struct {
	Decisions, Headings, Identifiers int
}

// DefaultSeedOpts keeps the seed small enough to run in a few seconds.
var DefaultSeedOpts = SeedOpts{Decisions: 60, Headings: 60, Identifiers: 40}

// decisionsPerRecord is how many decisions one record may contribute.
const decisionsPerRecord = 3

// Seed sections. Cases in any other section are the user's own and a reseed
// keeps them.
const (
	SectionDecision   = "seed-decision"
	SectionHeading    = "seed-heading"
	SectionIdentifier = "seed-ident"
	SectionHard       = "hard"
	SectionLegacy     = "legacy"
)

// IsSeedSection reports whether a section is regenerated by Seed.
func IsSeedSection(s string) bool { return strings.HasPrefix(s, "seed-") }

// Seed builds golden cases without any model call: the first decision of
// each session record, asked as "what did we decide about ...", labelled with
// that record; and a distinctive heading and code identifier from each repo
// doc, labelled with that doc. Headings and identifiers that occur in more
// than one doc are skipped, since another doc answering would be no miss.
// Sources are sampled in a fixed hash order, so the same store gives the same
// set and one owner's docs do not crowd out the rest.
func Seed(records, docs []SeedDoc, opts SeedOpts) []Case {
	var out []Case
	for _, r := range sample(records) {
		if countSection(out, SectionDecision) >= opts.Decisions {
			break
		}
		for _, d := range decisions(r.Text, decisionsPerRecord) {
			if countSection(out, SectionDecision) >= opts.Decisions {
				break
			}
			out = append(out, Case{Query: "what did we decide about " + d, Expect: []string{r.URI},
				Section: SectionDecision, Note: "a decision from the session record"})
		}
	}
	headCount, identCount := map[string]int{}, map[string]int{}
	perDoc := make([][2][]string, len(docs))
	lowered := make([]string, 0, len(docs)+len(records))
	for i, d := range docs {
		hs, ids := headings(d.Text), identifiers(d.Text)
		perDoc[i] = [2][]string{hs, ids}
		for _, h := range uniq(hs) {
			headCount[strings.ToLower(h)]++
		}
		for _, id := range uniq(ids) {
			identCount[strings.ToLower(id)] = 0
		}
		lowered = append(lowered, strings.ToLower(d.Text))
	}
	for _, r := range records {
		lowered = append(lowered, strings.ToLower(r.Text))
	}
	// An identifier counts as distinctive only if no other text names it at
	// all, backticked or not.
	for id := range identCount {
		for _, t := range lowered {
			if strings.Contains(t, id) {
				identCount[id]++
			}
		}
	}
	index := make(map[string]int, len(docs))
	for i, d := range docs {
		index[d.URI] = i
	}
	for _, d := range sample(docs) {
		hs, ids := perDoc[index[d.URI]][0], perDoc[index[d.URI]][1]
		if countSection(out, SectionHeading) < opts.Headings {
			for _, h := range hs {
				if headCount[strings.ToLower(h)] == 1 {
					out = append(out, Case{Query: h, Expect: []string{d.URI}, Section: SectionHeading, Note: "doc heading"})
					break
				}
			}
		}
		if countSection(out, SectionIdentifier) < opts.Identifiers {
			for _, id := range ids {
				if identCount[strings.ToLower(id)] == 1 {
					out = append(out, Case{Query: id, Expect: []string{d.URI}, Section: SectionIdentifier, Note: "identifier only this doc names"})
					break
				}
			}
		}
	}
	return dedupe(out)
}

// MergeSeed replaces the seed sections of a set with fresh seed cases,
// keeping every other case (hand-written ones) in place and first.
func MergeSeed(s Set, seed []Case) Set {
	var out Set
	for _, c := range s.Cases {
		if !IsSeedSection(c.Section) {
			out.Cases = append(out.Cases, c)
		}
	}
	out.Cases = dedupe(append(out.Cases, seed...))
	if len(out.Cases) > maxCases {
		out.Cases = out.Cases[:maxCases]
	}
	return out
}

func countSection(cs []Case, section string) int {
	n := 0
	for _, c := range cs {
		if c.Section == section {
			n++
		}
	}
	return n
}

// dedupe drops later cases repeating an earlier query.
func dedupe(cs []Case) []Case {
	seen := map[string]bool{}
	out := cs[:0:0]
	for _, c := range cs {
		k := strings.ToLower(strings.TrimSpace(c.Query))
		if seen[k] {
			continue
		}
		seen[k] = true
		out = append(out, c)
	}
	return out
}

func uniq(xs []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, x := range xs {
		k := strings.ToLower(x)
		if !seen[k] {
			seen[k] = true
			out = append(out, x)
		}
	}
	return out
}

// sample orders sources by a hash of their URI.
func sample(docs []SeedDoc) []SeedDoc {
	out := append([]SeedDoc(nil), docs...)
	key := func(s string) uint64 {
		h := fnv.New64a()
		_, _ = h.Write([]byte(s))
		return h.Sum64()
	}
	sort.SliceStable(out, func(i, j int) bool { return key(out[i].URI) < key(out[j].URI) })
	return out
}

var (
	mdLink     = regexp.MustCompile(`\[([^\]]*)\]\([^)]*\)`)
	mdEmphasis = regexp.MustCompile("[*`]+")
	leadNoise  = regexp.MustCompile(`^[^\pL]+`)
	headingRe  = regexp.MustCompile(`^#{2,3}\s+(.+?)\s*#*\s*$`)
	backticked = regexp.MustCompile("`([^`\\s]{6,64})`")
	identLike  = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9]*(?:[._/:-][A-Za-z0-9]+)+$|^[a-z]+[A-Z][A-Za-z0-9]*$|^[A-Z][a-z0-9]+[A-Z][A-Za-z0-9]*$`)
)

// plain strips the markdown that would only add noise to a query.
func plain(s string) string {
	s = mdLink.ReplaceAllString(s, "$1")
	s = mdEmphasis.ReplaceAllString(s, "")
	return strings.Join(strings.Fields(s), " ")
}

// maxQueryWords keeps a seeded decision question about as long as a person
// would type it, rather than the decision quoted whole.
const maxQueryWords = 10

// decisions returns up to n bullets under a "Decisions" heading, each cut at
// its first clause and to maxQueryWords words. Stored text sometimes joins a
// list onto one line ("- a - b"); those items are split apart again.
func decisions(text string, n int) []string {
	var out []string
	in := false
	for _, line := range strings.Split(text, "\n") {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, "#") {
			in = strings.EqualFold(strings.TrimSpace(strings.TrimLeft(t, "#")), "decisions")
			continue
		}
		if !in || !(strings.HasPrefix(t, "- ") || strings.HasPrefix(t, "* ")) {
			continue
		}
		for _, item := range strings.Split(t[2:], " - ") {
			if d := clause(item); d != "" {
				out = append(out, d)
				if len(out) == n {
					return out
				}
			}
		}
	}
	return out
}

// clause cuts a decision to its first clause, as a short question topic.
func clause(item string) string {
	d := plain(item)
	if i := strings.IndexAny(d, ".:;—("); i > 0 {
		d = d[:i]
	}
	words := strings.Fields(d)
	if len(words) < 3 {
		return ""
	}
	if len(words) > maxQueryWords {
		words = words[:maxQueryWords]
	}
	return strings.TrimRight(strings.Join(words, " "), ",")
}

// genericHeadings are section names nearly every doc has.
var genericHeadings = map[string]bool{"overview": true, "usage": true, "installation": true, "install": true,
	"license": true, "contributing": true, "testing": true, "summary": true, "introduction": true, "setup": true,
	"getting started": true, "requirements": true, "configuration": true, "development": true, "notes": true,
	"table of contents": true, "contents": true, "background": true, "goals": true, "non-goals": true,
	"open questions": true, "references": true, "examples": true, "example": true, "faq": true, "status": true}

// headings returns a doc's level-2 and level-3 headings of three to twelve
// words, outside code fences.
func headings(text string) []string {
	var out []string
	fence := false
	for _, line := range strings.Split(text, "\n") {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, "```") || strings.HasPrefix(t, "~~~") {
			fence = !fence
			continue
		}
		if fence {
			continue
		}
		m := headingRe.FindStringSubmatch(t)
		if m == nil {
			continue
		}
		h := leadNoise.ReplaceAllString(plain(m[1]), "")
		if n := len(strings.Fields(h)); n < 3 || n > 12 || genericHeadings[strings.ToLower(h)] {
			continue
		}
		out = append(out, h)
	}
	return out
}

// identifiers returns the code identifiers a doc names in backticks: dotted,
// slashed, snake_case or camelCase names, not plain words or numbers.
func identifiers(text string) []string {
	var out []string
	for _, m := range backticked.FindAllStringSubmatch(text, -1) {
		id := strings.Trim(m[1], "./:-")
		if len(id) >= 6 && identLike.MatchString(id) {
			out = append(out, id)
		}
	}
	return out
}
